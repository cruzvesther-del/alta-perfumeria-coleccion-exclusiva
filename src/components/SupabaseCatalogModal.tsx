import React, { useState } from 'react';
import { 
  Database, 
  X, 
  UploadCloud, 
  RefreshCw, 
  Check, 
  AlertCircle, 
  Copy, 
  Plus, 
  Layers, 
  ShieldCheck, 
  Table, 
  Sparkles,
  ExternalLink,
  Package
} from 'lucide-react';
import { 
  SupabaseProductRow, 
  saveCatalogToSupabase, 
  saveSingleProductToSupabase,
  PRODUCTS_TABLE 
} from '../lib/products-supabase';
import { Product } from '../types';
import { SUPABASE_URL } from '../lib/supabase';

interface SupabaseCatalogModalProps {
  isOpen: boolean;
  onClose: () => void;
  products: Product[];
  rawRows?: SupabaseProductRow[];
  source: 'supabase' | 'cache' | 'default';
  onRefresh: () => Promise<void>;
  onCatalogUpdated: () => void;
  isLoading: boolean;
}

export const SupabaseCatalogModal: React.FC<SupabaseCatalogModalProps> = ({
  isOpen,
  onClose,
  products,
  rawRows = [],
  source,
  onRefresh,
  onCatalogUpdated,
  isLoading
}) => {
  const [activeTab, setActiveTab] = useState<'status' | 'add' | 'sql'>('status');
  const [isSavingAll, setIsSavingAll] = useState(false);
  const [saveMessage, setSaveMessage] = useState<{ type: 'success' | 'error' | 'info'; text: string } | null>(null);
  const [copiedSql, setCopiedSql] = useState(false);

  // New product form state
  const [nuevoNombre, setNuevoNombre] = useState('');
  const [nuevoPrecio, setNuevoPrecio] = useState('');
  const [nuevaDescripcion, setNuevaDescripcion] = useState('');
  const [nuevaImagen, setNuevaImagen] = useState('');
  const [nuevoStock, setNuevoStock] = useState('15');
  const [isSubmittingNew, setIsSubmittingNew] = useState(false);

  if (!isOpen) return null;

  const sqlCode = `-- Tabla para el catálogo de perfumes de Esther Cruz Velásquez
CREATE TABLE IF NOT EXISTS public.productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  precio NUMERIC NOT NULL,
  descripcion TEXT,
  imagen TEXT,
  stock INTEGER DEFAULT 10,
  categoria TEXT,
  familia_olfativa TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- Habilitar permisos de lectura y escritura para la tienda
ALTER TABLE public.productos ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Lectura pública de productos" 
  ON public.productos FOR SELECT USING (true);

CREATE POLICY "Inserción pública de productos" 
  ON public.productos FOR INSERT WITH CHECK (true);

  ON public.productos FOR UPDATE USING (true);

-- Tabla para suscriptores al boletín de Esther Cruz Velásquez
CREATE TABLE IF NOT EXISTS public.suscriptores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.suscriptores ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Inserción pública de suscriptores" 
  ON public.suscriptores FOR INSERT WITH CHECK (true);

CREATE POLICY "Lectura de suscriptores" 
  ON public.suscriptores FOR SELECT USING (true);
`;

  const handleCopySql = () => {
    navigator.clipboard.writeText(sqlCode);
    setCopiedSql(true);
    setTimeout(() => setCopiedSql(false), 2500);
  };

  const handleSaveAllToSupabase = async () => {
    setIsSavingAll(true);
    setSaveMessage(null);
    try {
      const result = await saveCatalogToSupabase(products);
      if (result.success) {
        setSaveMessage({
          type: 'success',
          text: `¡Éxito! Se guardaron ${result.insertedCount} fragancias en la tabla 'productos' de Supabase.`
        });
        await onRefresh();
        onCatalogUpdated();
      } else {
        setSaveMessage({
          type: 'info',
          text: `Sincronización enviada (${result.error || 'Verifica si la tabla "productos" existe en tu Dashboard de Supabase'}). Se guardó una copia de respaldo en caché local.`
        });
      }
    } catch (e: any) {
      setSaveMessage({
        type: 'error',
        text: `Error al conectar con Supabase: ${e?.message || 'Error desconocido'}`
      });
    } finally {
      setIsSavingAll(false);
    }
  };

  const handleCreateProduct = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!nuevoNombre.trim() || !nuevoPrecio.trim()) return;

    setIsSubmittingNew(true);
    setSaveMessage(null);

    const priceNum = parseFloat(nuevoPrecio) || 200;
    const stockNum = parseInt(nuevoStock, 10) || 10;
    const imgUrl = nuevaImagen.trim() || '/images/perfume_dama_floral_1792432937694.jpg';

    const res = await saveSingleProductToSupabase({
      nombre: nuevoNombre.trim(),
      precio: priceNum,
      descripcion: nuevaDescripcion.trim() || 'Fragancia exclusiva de autor',
      imagen: imgUrl,
      stock: stockNum
    });

    setIsSubmittingNew(false);

    if (res.success) {
      setSaveMessage({
        type: 'success',
        text: `¡Fragancia "${nuevoNombre}" guardada con éxito en la tabla 'productos' de Supabase!`
      });
      setNuevoNombre('');
      setNuevoPrecio('');
      setNuevaDescripcion('');
      setNuevaImagen('');
      setNuevoStock('15');
      await onRefresh();
      onCatalogUpdated();
    } else {
      setSaveMessage({
        type: 'error',
        text: `No se pudo guardar en Supabase: ${res.error}. Puedes copiar el SQL para crear la tabla 'productos' en la pestaña "Script SQL".`
      });
    }
  };

  return (
    <div className="fixed inset-0 z-50 overflow-y-auto flex items-center justify-center p-4 bg-black/60 backdrop-blur-xs">
      <div className="bg-white rounded-3xl max-w-2xl w-full shadow-2xl border border-stone-200 overflow-hidden flex flex-col max-h-[90vh]">
        {/* Modal Header */}
        <div className="bg-[#1A1A1A] text-white p-5 sm:p-6 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-[#D4AF37]/20 border border-[#D4AF37]/30 flex items-center justify-center text-[#D4AF37]">
              <Database className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-lg font-serif-luxury font-bold">
                  Conexión Supabase · Catálogo de Productos
                </h3>
                <span className="text-[10px] px-2 py-0.5 rounded-full uppercase tracking-wider font-bold bg-[#D4AF37] text-stone-900">
                  Tabla '{PRODUCTS_TABLE}'
                </span>
              </div>
              <p className="text-stone-400 text-xs mt-0.5">
                Lectura y almacenamiento directo en la nube de Esther Cruz Velásquez
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="text-stone-400 hover:text-white p-2 rounded-xl hover:bg-white/10 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Navigation Tabs */}
        <div className="flex border-b border-stone-200 bg-[#FAF8F5] px-6 text-xs font-semibold text-stone-600">
          <button
            onClick={() => setActiveTab('status')}
            className={`py-3 px-4 border-b-2 flex items-center gap-2 transition-colors ${
              activeTab === 'status'
                ? 'border-[#8C6D23] text-[#8C6D23] font-bold'
                : 'border-transparent hover:text-stone-900'
            }`}
          >
            <Layers className="w-4 h-4" />
            <span>Estado y Sincronización ({products.length})</span>
          </button>

          <button
            onClick={() => setActiveTab('add')}
            className={`py-3 px-4 border-b-2 flex items-center gap-2 transition-colors ${
              activeTab === 'add'
                ? 'border-[#8C6D23] text-[#8C6D23] font-bold'
                : 'border-transparent hover:text-stone-900'
            }`}
          >
            <Plus className="w-4 h-4" />
            <span>Agregar Fragancia</span>
          </button>

          <button
            onClick={() => setActiveTab('sql')}
            className={`py-3 px-4 border-b-2 flex items-center gap-2 transition-colors ${
              activeTab === 'sql'
                ? 'border-[#8C6D23] text-[#8C6D23] font-bold'
                : 'border-transparent hover:text-stone-900'
            }`}
          >
            <Table className="w-4 h-4" />
            <span>Estructura SQL</span>
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-6 overflow-y-auto flex-1 space-y-5 text-sm text-stone-700">
          {/* Notifications */}
          {saveMessage && (
            <div
              className={`p-4 rounded-2xl text-xs flex items-start gap-3 border ${
                saveMessage.type === 'success'
                  ? 'bg-emerald-50 text-emerald-900 border-emerald-200'
                  : saveMessage.type === 'error'
                  ? 'bg-rose-50 text-rose-900 border-rose-200'
                  : 'bg-amber-50 text-amber-900 border-amber-200'
              }`}
            >
              {saveMessage.type === 'success' ? (
                <Check className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
              ) : (
                <AlertCircle className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
              )}
              <span className="leading-relaxed">{saveMessage.text}</span>
            </div>
          )}

          {/* TAB 1: STATUS & SYNC */}
          {activeTab === 'status' && (
            <div className="space-y-5">
              {/* Status Box */}
              <div className="p-4 rounded-2xl bg-stone-50 border border-stone-200 grid grid-cols-1 sm:grid-cols-3 gap-4 text-xs">
                <div>
                  <span className="text-stone-500 block mb-0.5">Destino Supabase:</span>
                  <div className="flex items-center gap-1.5 font-semibold text-stone-900 truncate">
                    <Database className="w-3.5 h-3.5 text-[#8C6D23]" />
                    <span className="truncate">{SUPABASE_URL.replace('https://', '')}</span>
                  </div>
                </div>

                <div>
                  <span className="text-stone-500 block mb-0.5">Tabla Destino:</span>
                  <span className="font-bold text-[#8C6D23] font-mono bg-white px-2 py-0.5 rounded border border-stone-200">
                    public.productos
                  </span>
                </div>

                <div>
                  <span className="text-stone-500 block mb-0.5">Origen Actual:</span>
                  <span
                    className={`inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full font-bold uppercase tracking-wider text-[10px] ${
                      source === 'supabase'
                        ? 'bg-emerald-100 text-emerald-800'
                        : source === 'cache'
                        ? 'bg-blue-100 text-blue-800'
                        : 'bg-stone-200 text-stone-700'
                    }`}
                  >
                    <span className="w-1.5 h-1.5 rounded-full bg-current animate-pulse" />
                    {source === 'supabase'
                      ? 'Nube Supabase'
                      : source === 'cache'
                      ? 'Caché Local Sincronizada'
                      : 'Catálogo de Autor'}
                  </span>
                </div>
              </div>

              {/* Action Buttons */}
              <div className="flex flex-col sm:flex-row gap-3">
                <button
                  type="button"
                  onClick={handleSaveAllToSupabase}
                  disabled={isSavingAll}
                  className="flex-1 py-3 px-4 bg-[#8C6D23] hover:bg-[#725719] text-white font-bold rounded-2xl flex items-center justify-center gap-2 shadow-sm transition-all disabled:opacity-50 text-xs sm:text-sm cursor-pointer"
                >
                  {isSavingAll ? (
                    <RefreshCw className="w-4 h-4 animate-spin text-white" />
                  ) : (
                    <UploadCloud className="w-4 h-4" />
                  )}
                  <span>
                    {isSavingAll ? 'Guardando en Supabase...' : 'Guardar Catálogo en Supabase'}
                  </span>
                </button>

                <button
                  type="button"
                  onClick={onRefresh}
                  disabled={isLoading}
                  className="py-3 px-4 bg-white border border-stone-300 hover:bg-stone-50 text-stone-800 font-semibold rounded-2xl flex items-center justify-center gap-2 transition-colors disabled:opacity-50 text-xs sm:text-sm cursor-pointer"
                >
                  <RefreshCw className={`w-4 h-4 text-stone-500 ${isLoading ? 'animate-spin' : ''}`} />
                  <span>Recargar desde Supabase</span>
                </button>
              </div>

              {/* Fields info */}
              <div className="bg-amber-50/60 border border-amber-200/80 rounded-2xl p-4 text-xs text-amber-900 space-y-1.5">
                <div className="flex items-center gap-2 font-bold text-amber-950">
                  <ShieldCheck className="w-4 h-4 text-amber-700" />
                  <span>Campos requeridos almacenados en la tabla 'productos':</span>
                </div>
                <div className="grid grid-cols-2 sm:grid-cols-5 gap-2 pt-1 font-mono text-[11px]">
                  <div className="bg-white p-2 rounded-xl border border-amber-200">
                    <span className="font-bold text-stone-900 block">nombre</span>
                    <span className="text-[10px] text-stone-500">TEXT</span>
                  </div>
                  <div className="bg-white p-2 rounded-xl border border-amber-200">
                    <span className="font-bold text-stone-900 block">precio</span>
                    <span className="text-[10px] text-stone-500">NUMERIC (S/)</span>
                  </div>
                  <div className="bg-white p-2 rounded-xl border border-amber-200">
                    <span className="font-bold text-stone-900 block">descripcion</span>
                    <span className="text-[10px] text-stone-500">TEXT</span>
                  </div>
                  <div className="bg-white p-2 rounded-xl border border-amber-200">
                    <span className="font-bold text-stone-900 block">imagen</span>
                    <span className="text-[10px] text-stone-500">URL / PATH</span>
                  </div>
                  <div className="bg-white p-2 rounded-xl border border-amber-200">
                    <span className="font-bold text-stone-900 block">stock</span>
                    <span className="text-[10px] text-stone-500">INTEGER</span>
                  </div>
                </div>
              </div>

              {/* Current catalog preview */}
              <div className="space-y-2">
                <span className="font-bold text-stone-900 text-xs flex items-center justify-between">
                  <span>Fragancias en el catálogo ({products.length}):</span>
                  <span className="text-stone-400 font-normal">Leídas en tiempo real</span>
                </span>
                <div className="max-h-56 overflow-y-auto space-y-2 pr-1 border border-stone-200 rounded-2xl p-2 bg-stone-50/50">
                  {products.map((p, idx) => (
                    <div
                      key={p.id || idx}
                      className="p-2.5 bg-white rounded-xl border border-stone-200/80 flex items-center justify-between gap-3 text-xs"
                    >
                      <div className="flex items-center gap-3 min-w-0">
                        <img
                          src={p.image}
                          alt={p.name}
                          className="w-10 h-10 object-cover rounded-lg border border-stone-100 shrink-0"
                          onError={(e) => {
                            (e.target as any).src = '/images/perfume_dama_floral_1792432937694.jpg';
                          }}
                        />
                        <div className="min-w-0">
                          <h4 className="font-semibold text-stone-900 truncate">{p.name}</h4>
                          <p className="text-stone-500 text-[11px] truncate">
                            {p.description || p.tagline}
                          </p>
                        </div>
                      </div>
                      <div className="text-right shrink-0">
                        <span className="font-bold text-stone-900 font-mono">
                          S/ {(p.sizes[p.defaultSizeIndex]?.price || p.sizes[0]?.price || 0).toFixed(2)}
                        </span>
                        <span className="block text-[10px] text-emerald-700 font-medium">
                          Stock: {p.sizes[0]?.inStock ? 'Disponible' : 'Agotado'}
                        </span>
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            </div>
          )}

          {/* TAB 2: ADD PRODUCT FORM */}
          {activeTab === 'add' && (
            <form onSubmit={handleCreateProduct} className="space-y-4">
              <div className="bg-stone-50 p-3.5 rounded-2xl border border-stone-200 text-xs text-stone-600">
                Guarda una nueva fragancia directamente en la tabla <strong className="text-stone-900">productos</strong> de Supabase con los campos requeridos:
              </div>

              <div>
                <label className="block text-xs font-bold text-stone-800 mb-1">
                  Nombre de la Fragancia *
                </label>
                <input
                  type="text"
                  required
                  placeholder="Ej. Oud Imperial & Rosa Damascena"
                  value={nuevoNombre}
                  onChange={(e) => setNuevoNombre(e.target.value)}
                  className="w-full px-3.5 py-2.5 bg-white border border-stone-200 rounded-xl text-xs text-stone-900 focus:outline-none focus:border-[#8C6D23]"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-bold text-stone-800 mb-1">
                    Precio en Soles (S/) *
                  </label>
                  <input
                    type="number"
                    step="0.10"
                    required
                    placeholder="340.00"
                    value={nuevoPrecio}
                    onChange={(e) => setNuevoPrecio(e.target.value)}
                    className="w-full px-3.5 py-2.5 bg-white border border-stone-200 rounded-xl text-xs text-stone-900 focus:outline-none focus:border-[#8C6D23]"
                  />
                </div>

                <div>
                  <label className="block text-xs font-bold text-stone-800 mb-1">
                    Unidades en Stock *
                  </label>
                  <input
                    type="number"
                    required
                    placeholder="15"
                    value={nuevoStock}
                    onChange={(e) => setNuevoStock(e.target.value)}
                    className="w-full px-3.5 py-2.5 bg-white border border-stone-200 rounded-xl text-xs text-stone-900 focus:outline-none focus:border-[#8C6D23]"
                  />
                </div>
              </div>

              <div>
                <label className="block text-xs font-bold text-stone-800 mb-1">
                  Descripción olfativa / Notas
                </label>
                <textarea
                  rows={3}
                  placeholder="Elixir concentrado con notas de madera de agar, resina de benjuí y flores de Grasse..."
                  value={nuevaDescripcion}
                  onChange={(e) => setNuevaDescripcion(e.target.value)}
                  className="w-full px-3.5 py-2.5 bg-white border border-stone-200 rounded-xl text-xs text-stone-900 focus:outline-none focus:border-[#8C6D23]"
                />
              </div>

              <div>
                <label className="block text-xs font-bold text-stone-800 mb-1">
                  URL de Imagen del Perfume
                </label>
                <input
                  type="text"
                  placeholder="https://... o ruta local"
                  value={nuevaImagen}
                  onChange={(e) => setNuevaImagen(e.target.value)}
                  className="w-full px-3.5 py-2.5 bg-white border border-stone-200 rounded-xl text-xs text-stone-900 focus:outline-none focus:border-[#8C6D23]"
                />
                <span className="text-[10px] text-stone-400 mt-1 block">
                  Si se deja en blanco, se asignará automáticamente una fotografía de alta resolución de la boutique.
                </span>
              </div>

              <div className="pt-2">
                <button
                  type="submit"
                  disabled={isSubmittingNew}
                  className="w-full py-3 px-4 bg-[#1A1A1A] hover:bg-[#2E2E2E] text-white font-bold rounded-2xl flex items-center justify-center gap-2 shadow-sm text-xs sm:text-sm transition-all disabled:opacity-50 cursor-pointer"
                >
                  {isSubmittingNew ? (
                    <RefreshCw className="w-4 h-4 animate-spin text-white" />
                  ) : (
                    <Plus className="w-4 h-4 text-[#D4AF37]" />
                  )}
                  <span>
                    {isSubmittingNew ? 'Guardando en Supabase...' : 'Guardar Fragancia en Supabase'}
                  </span>
                </button>
              </div>
            </form>
          )}

          {/* TAB 3: SQL SCHEMA */}
          {activeTab === 'sql' && (
            <div className="space-y-4">
              <div className="text-xs text-stone-600 leading-relaxed">
                Si aún no has creado la tabla <strong className="text-stone-900 font-mono">productos</strong> en tu consola de Supabase, puedes copiar este código SQL y ejecutarlo en el <span className="font-semibold text-stone-900">SQL Editor</span> de Supabase:
              </div>

              <div className="relative">
                <pre className="bg-[#1A1A1A] text-[#FAF8F5] p-4 rounded-2xl text-[11px] font-mono overflow-x-auto leading-relaxed border border-stone-800">
                  {sqlCode}
                </pre>
                <button
                  type="button"
                  onClick={handleCopySql}
                  className="absolute top-3 right-3 px-3 py-1.5 bg-white/10 hover:bg-white/20 text-white rounded-xl text-xs flex items-center gap-1.5 font-medium transition-colors"
                >
                  {copiedSql ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                      <span className="text-emerald-300">¡Copiado!</span>
                    </>
                  ) : (
                    <>
                      <Copy className="w-3.5 h-3.5 text-stone-300" />
                      <span>Copiar SQL</span>
                    </>
                  )}
                </button>
              </div>
            </div>
          )}
        </div>

        {/* Modal Footer */}
        <div className="p-4 bg-stone-50 border-t border-stone-200 flex items-center justify-between text-xs text-stone-500">
          <span className="flex items-center gap-1.5">
            <Sparkles className="w-3.5 h-3.5 text-[#D4AF37]" />
            <span>Esther Cruz Velásquez · Boutique de Perfumería</span>
          </span>
          <button
            onClick={onClose}
            className="px-4 py-2 bg-stone-200 hover:bg-stone-300 text-stone-800 rounded-xl font-semibold transition-colors"
          >
            Cerrar
          </button>
        </div>
      </div>
    </div>
  );
};
